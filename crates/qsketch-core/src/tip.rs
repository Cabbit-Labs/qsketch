    #[test]
    fn small_dabs_read_a_prefiltered_tip() {
        // A 64 × 64 checkerboard of single texels: at 1 texel per pixel it is
        // the checkerboard, shrunk it has to average to gray.
        let alpha = (0..64 * 64).map(|i| ((i % 64 + i / 64) % 2) as f32).collect();
        let t = TipImage::from_alpha("checks", 64, 64, alpha);
        assert_eq!(t.lod_for_radius(32.0), 0.0);
        assert_eq!(t.lod_for_radius(40.0), 0.0);
        // 8 texels to a pixel: level 3.
        let lod = t.lod_for_radius(4.0);
        assert!((lod - 3.0).abs() < 1e-3, "radius 4 should use level 3, got {lod}");
        for (nx, ny) in [(-0.3, 0.2), (0.1, 0.1), (0.4, -0.4)] {
            let v = t.sample_tip_lod(nx, ny, lod);
            assert!((v - 0.5).abs() < 0.05, "{v} at {nx}, {ny}");
        }
        assert_eq!(t.sample_tip_lod(0.2, 0.1, 0.0), t.sample_tip(0.2, 0.1));
        // Levels get coarser as the dab gets smaller.
        assert!(t.lod_for_radius(2.0) >= t.lod_for_radius(8.0));
    }

